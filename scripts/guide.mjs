// Build-time rendering only: one authored source set, no recovery runtime.
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const INPUTS = ['guide/source.md', 'guide/metadata.json', 'guide/compass.svg', 'scripts/guide.mjs', 'package.json'];
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');
const json = (value) => JSON.stringify(value, null, 2) + '\n';
function sourceIdentity(root) {
  const git = (...args) => execFileSync('git', ['-C', root, ...args], { encoding: 'utf8', windowsHide: true, timeout: 10000 }).trim();
  return { repository: 'https://github.com/samartomar/aih-extensions',
    commit: git('log', '-1', '--format=%H', '--', ...INPUTS),
    dirty: git('status', '--porcelain', '--', ...INPUTS) !== '' };
}
export function renderGuide(root = ROOT) {
  const metadata = JSON.parse(fs.readFileSync(path.join(root, 'guide/metadata.json')));
  const version = JSON.parse(fs.readFileSync(path.join(root, 'package.json'))).version;
  const inputs = Object.fromEntries(INPUTS.map(file => [file, hash(fs.readFileSync(path.join(root, file)))]));
  const source = { ...sourceIdentity(root), sha256: hash(json(inputs)) };
  const identity = `Extensions ${version} · source ${source.commit}${source.dirty ? ' (uncommitted source set)' : ''}\nSource-set SHA-256: \`${source.sha256}\`. Exact file hashes: \`manifest.json\`.\n`;
  const body = `# 🧭 ${metadata.name}\n\n${metadata.description}\n\n${identity}\n` + fs.readFileSync(path.join(root, 'guide/source.md'), 'utf8').replace(/\r\n/g, '\n');
  const fm = `name: ${metadata.id}\ndescription: ${JSON.stringify(metadata.description)}\n`;
  const files = {
    'guide/MANUAL.md': '<!-- Generated by npm run guide; edit guide/source.md. -->\n' + body,
    'guide/generated/claude/aih-guide.md': `---\n${fm}---\n\nYou are Ask AIH Guide. Carry the user's recovery conversation through the following loop, using ordinary available tools and preserving their permissions and project instructions.\n\n${body}`,
    'guide/generated/kimi/aih-guide.md': `---\n${fm}---\n\n\${base_prompt}\n\nYou are Ask AIH Guide. Use this recovery loop in the current conversation.\n\n${body}`,
    'guide/generated/opencode/aih-guide.md': `---\n${fm}mode: primary\n---\n\nYou are Ask AIH Guide. Use this recovery loop in the current conversation with the existing tools, permissions and project instructions.\n\n${body}`,
  };
  const hashes = Object.fromEntries(Object.entries(files).map(([file, text]) => [file, hash(text)]));
  hashes['guide/compass.svg'] = inputs['guide/compass.svg'];
  files['guide/manifest.json'] = json({ ...metadata, version, source, inputs, files: hashes });
  return files;
}

// Verify bytes before distributing a saved guide; works without Git in a release copy.
export function verifyGuide(root = ROOT) {
  const manifest = JSON.parse(fs.readFileSync(path.join(root, 'guide/manifest.json'), 'utf8'));
  const version = JSON.parse(fs.readFileSync(path.join(root, 'package.json'))).version;
  if (manifest.version !== version) throw new Error('guide version is stale; run npm run guide');
  for (const [file, expected] of Object.entries({ ...manifest.inputs, ...manifest.files })) {
    if (hash(fs.readFileSync(path.join(root, file))) !== expected) throw new Error(`guide bytes changed: ${file}; run npm run guide`);
  }
  return manifest;
}

const invoked = process.argv[1] && path.resolve(process.argv[1]).toLowerCase() === fileURLToPath(import.meta.url).toLowerCase();
if (invoked) {
  const files = renderGuide();
  for (const [file, text] of Object.entries(files)) {
    const dest = path.join(ROOT, file);
    if (process.argv.includes('--check')) {
      if (!fs.existsSync(dest) || fs.readFileSync(dest, 'utf8') !== text) throw new Error(`stale guide output: ${file}; run npm run guide`);
    } else {
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      fs.writeFileSync(dest, text);
    }
  }
  console.log(`guide: ${process.argv.includes('--check') ? 'verified' : 'generated'} ${Object.keys(files).length} files`);
}
